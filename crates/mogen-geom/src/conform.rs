    #[test]
    fn patch_anchor_dir_overrides_surface_normal() {
        // Even on a flat plane, providing a custom anchor_dir flips the
        // patch's outward direction — vertices end up on the negative-Y
        // side of the plane instead of +Y.
        let plane = plane_mesh([4.0, 4.0], UvMode::default());
        let surface = SurfaceIndex::build(&plane);
        let disc = crate::primitives::disc_mesh(0.2, 16, UvMode::default());
        let params = PatchParams {
            up: Axis::Y,
            anchor: Vec3::ZERO,
            anchor_dir: Some(Vec3::new(0.0, -1.0, 0.0)),
            roll_ref: None,
            lift: 0.05,
        };
        // anchor_dir only sets the orienting frame; per-vertex height uses
        // the *surface* normal at the snapped point. So the disc still sits
        // at +y (plane faces +Y), but its in-plane axes flip — verify the
        // frame change by checking that t0/b0 still produce a planar disc.
        let out = conform_patch(&disc, &surface, &params);
        for p in &out.positions {
            assert!((p[1] - 0.05).abs() < 1e-3, "vertex y {} not at lift", p[1]);
        }
    }
