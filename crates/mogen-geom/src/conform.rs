    fn flat_strip(len_x: f32, width_z: f32, height_y: f32) -> Mesh {
        // A simple unit box centered at origin with the given dimensions.
        crate::primitives::box_mesh([len_x, height_y, width_z], UvMode::default())
    }

    #[test]
    fn flat_target_is_near_identity_modulo_rigid_transform() {
        // Conform a flat strip onto a flat plane: the deformed mesh should
        // look like the original strip just rigidly placed onto the plane,
        // not warped.
        let plane = plane_mesh([4.0, 4.0], UvMode::default());
        let surface = SurfaceIndex::build(&plane);

        let strip = flat_strip(2.0, 0.2, 0.04);

        // Place the path along +X at the plane (y=0). The chord runs from
        // (-1, 0, 0) to (1, 0, 0); both endpoints already lie on the plane.
        let frames = build_path_frames(&surface, Vec3::new(-1.0, 0.0, 0.0), Vec3::new(1.0, 0.0, 0.0), 32, 0.0);
        assert_eq!(frames.len(), 32);

        let params = ConformParams {
            axes: AxisMap::from_along(Axis::X),
            lift: 0.0,
        };
        let out = conform_mesh(&strip, &frames, &params);

        assert_eq!(out.positions.len(), strip.positions.len());
        // Every output vertex's distance to the plane (|y| since plane lies
        // at y=0) should equal its original |y| ± numerical noise — i.e.,
        // the height-axis offsets are preserved.
        for (orig, new) in strip.positions.iter().zip(out.positions.iter()) {
            let dy_orig = orig[1].abs();
            let dy_new = new[1].abs();
            assert!(
                (dy_orig - dy_new).abs() < 1e-3,
                "vertex y mismatch: orig={dy_orig}, new={dy_new}",
            );
        }
    }

    #[test]
    fn conform_to_sphere_lifts_along_radial_normal() {
        // A flat strip conformed onto the equator of a sphere should have
        // every vertex sit at radius (1.0 + lift) from the sphere's centre,
        // give or take the strip's own thickness in the height axis.
        let sphere = sphere_mesh(1.0, 16, 24, UvMode::default());
        let surface = SurfaceIndex::build(&sphere);

        // Strip 1m long, 2cm wide, 1mm thick. Path runs across the equator
        // (y=0) from -X to +X.
        let strip = crate::primitives::box_mesh([1.0, 0.001, 0.02], UvMode::default());
        let frames = build_path_frames(
            &surface,
            Vec3::new(-1.0, 0.0, 0.0),
            Vec3::new(1.0, 0.0, 0.0),
            64,
            0.0,
        );

        let params = ConformParams {
            axes: AxisMap::from_along(Axis::X),
            lift: 0.005,
        };
        let out = conform_mesh(&strip, &frames, &params);

        // Sphere radius 1, lift 5mm, strip half-thickness ≤ 0.5mm. So every
        // vertex sits at distance 1.0050 ± ~0.001 from the origin.
        for p in &out.positions {
            let r = Vec3::from_array(*p).length();
            assert!(
                (r - 1.005).abs() < 0.01,
                "vertex radius {r} far from expected ~1.005",
            );
        }
    }

