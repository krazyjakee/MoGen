    #[test]
    fn subdivide_box_increases_distinct_along_axis() {
        let strip = crate::primitives::box_mesh([1.0, 0.01, 0.05], UvMode::default());
        // Bare box has only two distinct X positions (the two end faces).
        let xs0: std::collections::BTreeSet<i64> =
            strip.positions.iter().map(|p| (p[0] * 1e4) as i64).collect();
        assert_eq!(xs0.len(), 2);

        let dense = subdivide_along_axis(&strip, Axis::X, 16);
        let xs1: std::collections::BTreeSet<i64> =
            dense.positions.iter().map(|p| (p[0] * 1e4) as i64).collect();
        assert!(
            xs1.len() >= 17,
            "expected at least 17 distinct x values after subdivide, got {}",
            xs1.len()
        );

        // Indices remain a multiple of 3 (still a triangle list).
        assert_eq!(dense.indices.len() % 3, 0);
        // Every index references a real vertex.
        for &i in &dense.indices {
            assert!((i as usize) < dense.positions.len());
        }
    }

    #[test]
    fn subdivide_preserves_extent_and_volume() {
        let strip = crate::primitives::box_mesh([2.0, 0.1, 0.4], UvMode::default());
        let dense = subdivide_along_axis(&strip, Axis::X, 8);
        // AABB unchanged.
        let aabb = |m: &Mesh, axis: usize| -> (f32, f32) {
            let mut lo = f32::INFINITY;
            let mut hi = f32::NEG_INFINITY;
            for p in &m.positions {
                lo = lo.min(p[axis]);
                hi = hi.max(p[axis]);
            }
            (lo, hi)
        };
        for axis in 0..3 {
            let a = aabb(&strip, axis);
            let b = aabb(&dense, axis);
            assert!((a.0 - b.0).abs() < 1e-5 && (a.1 - b.1).abs() < 1e-5);
        }
    }

