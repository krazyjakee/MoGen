//! `python/mogen/_kinds.py` is generated from the validator's kind schema so
//! the Python builders (`mogen.box(...)`, …) can't drift from the language.
//! Regenerate with `MOGEN_GOLDENS_UPDATE=1 cargo test -p mogen-py`.

use std::path::Path;

/// Python keywords that are also `.mog` kinds get a trailing underscore.
const PY_KEYWORDS: &[&str] = &["if", "else", "for", "import", "from", "in", "is", "not", "and",
    "or", "with", "as", "def", "class", "return", "pass", "lambda", "global", "try", "while",
    "yield", "del", "assert", "break", "continue", "except", "finally", "raise", "async",
    "await", "nonlocal", "True", "False", "None"];

/// Names already taken by `mogen._core` exports; those kinds stay reachable
/// through `mogen.node("<kind>", …)`.
const RESERVED: &[&str] = &["node", "ref", "expr", "ident", "face", "gradient", "units", "load",
    "loads"];

fn render() -> String {
    let mut out = String::from(
        "# @generated by crates/mogen-py/tests/python_builders.rs from the compiler's kind\n\
         # schema. Do not edit: run `MOGEN_GOLDENS_UPDATE=1 cargo test -p mogen-py`.\n\
         \"\"\"One builder per `.mog` node kind. Inside ``with node:`` / ``with doc:``\n\
         each call appends to that parent; otherwise it returns a detached node.\"\"\"\n\n\
         from __future__ import annotations\n\n\
         from typing import Any, Optional\n\n\
         from ._core import Node, node\n\n",
    );
    let mut names = Vec::new();
    for kind in mogen_validate::KNOWN_KINDS {
        if RESERVED.contains(kind) {
            continue;
        }
        let py = if PY_KEYWORDS.contains(kind) { format!("{kind}_") } else { kind.to_string() };
        let attrs = mogen_validate::attrs_for_kind(kind);
        let doc = if attrs.is_empty() {
            format!("A ``{kind}`` node. See docs/dsl.md.")
        } else {
            let mut lines = vec![format!("A ``{kind}`` node. See docs/dsl.md.\n\n    Attributes:")];
            let mut line = String::from("   ");
            for a in attrs {
                if line.len() + a.len() > 76 {
                    lines.push(line);
                    line = String::from("   ");
                }
                line.push_str(&format!(" {a},"));
            }
            lines.push(line.trim_end_matches(',').to_string());
            lines.join("\n    ")
        };
        out.push_str(&format!(
            "\ndef {py}(name: Optional[str] = None, /, **attrs: Any) -> Node:\n    \"\"\"{doc}\n    \"\"\"\n    return node({kind:?}, name, **attrs)\n\n"
        ));
        names.push(py);
    }
    out.push_str("\n__all__ = [\n");
    for n in names {
        out.push_str(&format!("    {n:?},\n"));
    }
    out.push_str("]\n");
    out
}

#[test]
fn generated_builders_are_up_to_date() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("python/mogen/_kinds.py");
    let want = render();
    if std::env::var_os("MOGEN_GOLDENS_UPDATE").is_some() {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{} is stale; run `MOGEN_GOLDENS_UPDATE=1 cargo test -p mogen-py`",
        path.display()
    );
}
